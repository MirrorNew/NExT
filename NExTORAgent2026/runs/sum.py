def count_true_pass_flags(folder_path):
    """
    遍历 folder_path 下所有 .txt 文件，
    将其当作 JSON 解析并统计 evaluation.pass_flag == True 的总数。
    """
    folder = Path(folder_path)
    if not folder.is_dir():
        raise ValueError(f"指定路径不是文件夹: {folder_path}")
    cr = []
    fr = []
    total = 0
    total_f = 0
    # 遍历所有 *.txt 文件
    for txt_file in folder.glob("*.txt"):
        try:
            with txt_file.open("r", encoding="utf-8") as f:
                data = json.load(f)
        except Exception as e:
            print(f"[跳过] 读取或解析 JSON 出错：{txt_file} ，原因：{e}", file=sys.stderr)
            continue
        if data["evaluation"]["correct_flag"] is True:
            cr.append(data["entry"]["index"])
        else:
            fr.append(data["entry"]["index"])

            # print(data["entry"]["index"])
        eval_field = data.get("evaluation")
        # 情况 A：evaluation 是一个 dict
        if isinstance(eval_field, dict):
            if eval_field.get("correct_flag") is True:
                total += 1
            else:
                total_f += 1

        # if str(data["entry"]["index"] - 1) in index_fasle_58:
        #     if data["evaluation"]["correct_flag"] is True:
        #         a_in_b.append(data["entry"]["index"] - 1)
        # 其它类型：忽略
    return total, total_f,cr, fr



